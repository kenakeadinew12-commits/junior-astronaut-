// Entry flow + sound settings + Mission Control comms, in headless Chromium (test bundle with three-shim). Shots -> test-output/shots/entry-*.png
import { createRequire } from 'node:module';
import path from 'node:path'; import { mkdirSync } from 'node:fs'; import { fileURLToPath } from 'node:url';
import { serve } from './test-serve.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const here = path.dirname(fileURLToPath(import.meta.url));
mkdirSync(path.join(here, 'test-output', 'shots'), { recursive: true });
const s = await serve(path.join(here, 'test-output', 'dist-test'));
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--use-gl=angle'] });
const results = [], errs = [];
const check = (n, ok, d = '') => { results.push(!!ok); console.log((ok ? 'PASS ' : 'FAIL ') + n + (d ? '  ' + d : '')); };
const pg = await b.newPage({ viewport: { width: 1100, height: 650 } });
pg.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message));
pg.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errs.push('console.error ' + m.text()); });
// record text-to-speech calls (headless Chromium may have no voices)
await pg.addInitScript(() => {
  window.__spoken = [];
  const fake = { speak: (u) => window.__spoken.push(u.text), cancel() {}, getVoices: () => [] };
  Object.defineProperty(window, 'speechSynthesis', { value: fake, configurable: true });
  window.SpeechSynthesisUtterance = function (t) { this.text = t; };
});
const shot = (n) => pg.screenshot({ path: path.join(here, 'test-output', 'shots', `entry-${n}.png`), timeout: 90000 }).catch(() => {});
await pg.goto(`http://localhost:${s.address().port}/?debug&quality=0.4&scale=0.4&noshadow&noaa`);
await pg.waitForSelector('.screen.intro', { timeout: 60000 });
check('intro (rocket loading screen) is shown first', true);
const first = await pg.evaluate(() => Number(document.querySelector('.intro [role=progressbar]')?.getAttribute('aria-valuenow')));
check('progress starts low (not already 100)', first >= 1 && first < 100, 'first value ' + first);
await pg.waitForSelector('.intro .pct', { timeout: 60000 });
await pg.waitForFunction(() => /^100%/.test(document.querySelector('.intro .pct')?.textContent || ''), null, { timeout: 120000 });
const frames = await pg.evaluate(() => window.__lunar.frames);
check('loading reaches 100% only after real rendered frames', frames >= 90, 'frames ' + frames);
await shot('1-ready');
check('a Launch button is offered at 100%', await pg.locator('.intro button.primary').count() === 1);
await pg.click('.intro button.primary');
await pg.waitForFunction(() => document.querySelector('.intro .count')?.textContent === '3');
check('countdown starts at 3', true);
await pg.waitForSelector('.screen.intro.lifted', { timeout: 30000 });
check('liftoff: rocket animation class applied', await pg.evaluate(() => document.querySelector('.screen.intro')?.classList.contains('lifted')));
check('the intro shows no LIFTOFF text and no NASA banner, only the rocket', await pg.evaluate(() => !/lift\s*off|NASA SPACE APPS/i.test(document.querySelector('.screen.intro').innerText)));
await shot('2-liftoff');
await pg.waitForSelector('.screen.title', { timeout: 30000 });
await pg.waitForFunction(() => !document.querySelector('.screen.intro'), null, { timeout: 30000 });
check('intro is gone and the main menu is visible', await pg.locator('.screen.title').count() === 1);
const items = await pg.evaluate(() => [...document.querySelectorAll('nav.menu .btn')].map((x) => x.firstChild.textContent.trim()));
check('menu has Play, Select mission, Settings, About', ['Play', 'Select mission', 'Settings', 'About'].every((x) => items.includes(x)), items.join(' | '));
await shot('3-menu');
check('menu music mode is on in the main menu', await pg.evaluate(() => window.__lunar.sfx.musicMode === 'menu'));
// settings
await pg.click('nav.menu .btn:has-text("Settings")');
await pg.waitForSelector('input[type=range]');
await pg.evaluate(() => { const r = document.querySelector('input[type=range]'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(r, '35'); r.dispatchEvent(new Event('input', { bubbles: true })); });
await pg.waitForFunction(() => Math.abs(window.__lunar.sfx.volume - 0.35) < 0.01);
check('volume slider changes the audio master volume', true);
await pg.click('input[type=checkbox] >> nth=0'); await pg.waitForFunction(() => window.__lunar.sfx.muted === true);
check('mute checkbox mutes', true);
await pg.click('input[type=checkbox] >> nth=0'); await pg.waitForFunction(() => window.__lunar.sfx.muted === false);
check('saved settings persist in localStorage', await pg.evaluate(() => JSON.parse(localStorage.getItem('lunar_settings')).volume === 0.35));
await pg.evaluate(() => { const r = document.querySelectorAll('input[type=range]')[1]; const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(r, '20'); r.dispatchEvent(new Event('input', { bubbles: true })); });
await pg.waitForFunction(() => Math.abs(window.__lunar.sfx.musicVol - 0.2) < 0.01);
check('music volume slider works and is saved', await pg.evaluate(() => JSON.parse(localStorage.getItem('lunar_settings')).musicVol === 0.2));
await pg.keyboard.press('Escape'); await pg.waitForSelector('nav.menu');
await pg.click('nav.menu .btn:has-text("Select mission")'); await pg.waitForSelector('.lgrid');
check('no Easy/Normal/Hard selector on the level-select screen', await pg.locator('.diffbox').count() === 0 && !/Easy|Hard/.test(await pg.locator('.page').innerText()));
await pg.keyboard.press('Escape'); await pg.waitForSelector('nav.menu');
await pg.click('nav.menu .btn:has-text("About")'); await pg.waitForSelector('[aria-label=About]');
check('About screen opens', true);
await pg.keyboard.press('Escape'); await pg.waitForSelector('nav.menu');
// Play -> real game
await pg.click('nav.menu .btn.primary'); await pg.waitForFunction(() => window.__lunar.game.phase === 'briefing');
await pg.evaluate(() => window.__lunar.begin()); await pg.waitForFunction(() => window.__lunar.game.phase === 'playing');
check('Play launches the real game (phase playing, level 1)', await pg.evaluate(() => window.__lunar.game.level.id === 1));
await pg.waitForFunction(() => window.__lunar.sfx.musicMode === 'game', null, { timeout: 60000 }).catch(() => {});
check('game music switches to the mission theme', await pg.evaluate(() => window.__lunar.sfx.musicMode === 'game'));
check('no robot and no teammate exist in the 3D world or the game state', await pg.evaluate(() => window.__lunar.world.robot === undefined && window.__lunar.world.mate === undefined && window.__lunar.game.mate === undefined));
await pg.evaluate(() => { const p = window.__lunar.game.player; p.x = -4.6; p.z = -5.2; p.yaw = Math.PI; p.pitch = -0.1; });
await pg.waitForTimeout(800);
check('standing where the robot used to be gives no robot prompt', await pg.evaluate(() => !window.__lunar.prompt || !/ARIA|robot|teammate/i.test(window.__lunar.prompt.text)));
// the oxygen bug: standing in the habitat must not refill the suit
await pg.evaluate(() => { const g = window.__lunar.game; g.oxygen = 50; g.stats.minOxygen = 50; g.player.x = 0; g.player.z = -6; window.__t0 = g.time; });
await pg.waitForFunction(() => window.__lunar.game.time > window.__t0 + 4, null, { timeout: 120000 });
check('inside the habitat the suit oxygen does NOT jump back to 100% and the objective stays open', await pg.evaluate(() => { const g = window.__lunar.game; return Math.round(g.oxygen) === 50 && !g.flags.refilled && !g.objDone.refill; }));
check('the HUD oxygen number matches the game state', await pg.evaluate(() => /50/.test(document.querySelector('.hud')?.innerText || document.body.innerText)));
// Mission Control comms panel (3 fictional contacts, 4 predefined questions, no typing)
await pg.keyboard.press('KeyC'); await pg.waitForFunction(() => window.__lunar.game.phase === 'comms');
await pg.waitForSelector('.contacts');
check('C opens the comms panel and pauses the game', true);
check('three contacts are offered with name and role', await pg.locator('.contact').count() === 3 && /Marsh/.test(await pg.locator('.contacts').innerText()) && /Life-Support Engineer/.test(await pg.locator('.contacts').innerText()) && /Science Officer/.test(await pg.locator('.contacts').innerText()));
check('there is no free-text input anywhere in the panel', await pg.locator('.chat-panel input, .chat-panel textarea').count() === 0);
check('questions are disabled until a contact is chosen; exactly four exist', await pg.locator('.quick .btn').count() === 4 && await pg.locator('.quick .btn[disabled]').count() === 4);
check('the fictional / simulated disclaimer is shown', /not real NASA personnel/i.test(await pg.locator('.chat-panel').innerText()) && /not live communication/i.test(await pg.locator('.chat-panel').innerText()));
await pg.locator('.contact').nth(1).click();
await pg.locator('.quick .btn').nth(1).click();
await pg.waitForFunction(() => /refill station/i.test(document.querySelector('.chat-log')?.innerText || ''));
const a1 = await pg.locator('.chat-log').innerText();
check('the Life-Support Engineer answers the chosen level-1 question with an authored reply', /Okafor/.test(a1) && /How do I refill my suit oxygen\?/.test(a1));
await pg.waitForFunction(() => window.__spoken.length >= 1);
check('the reply is spoken (single voice)', await pg.evaluate(() => /refill station/i.test(window.__spoken[window.__spoken.length - 1])));
await shot('4-comms');
await pg.locator('.contact').nth(0).click(); await pg.locator('.quick .btn').nth(1).click();
await pg.waitForFunction(() => /Marsh/.test(document.querySelector('.chat-log')?.innerText || '') && document.querySelectorAll('.chat-log p.aria').length === 2);
const a2 = await pg.locator('.chat-log p.aria').nth(1).innerText();
check('a different contact gives a different answer to the same question', a2 !== await pg.locator('.chat-log p.aria').nth(0).innerText());
await pg.keyboard.press('Escape'); await pg.waitForFunction(() => window.__lunar.game.phase === 'playing');
check('Esc closes the panel and resumes', true);
// countdown tick during a timed question
await pg.evaluate(() => { const g = window.__lunar.game; g.collectedTotal = 2; g.time = Math.max(g.time, 20); });
await pg.waitForFunction(() => window.__lunar.game.phase === 'decision', null, { timeout: 90000 });
const t0 = await pg.evaluate(() => window.__lunar.sfx.ticksDue || 0);
await pg.waitForFunction((n) => (window.__lunar.sfx.ticksDue || 0) >= n + 2, t0, { timeout: 60000 });
check('ticking runs during the timed question', true);
const letters = await pg.locator('.choice b').allInnerTexts(); check('choices are lettered A-D in order', letters.join('') === 'ABCD', letters.join(''));
await pg.locator('.choice').first().click(); await pg.waitForFunction(() => window.__lunar.game.event?.state === 'result');
const t1 = await pg.evaluate(() => window.__lunar.sfx.ticksDue || 0); await pg.waitForTimeout(2500);
check('ticking stops as soon as the player answers', await pg.evaluate(() => window.__lunar.sfx.ticksDue || 0) === t1);
await pg.keyboard.press('Space').catch(() => {}); await pg.locator('.decision .btn.primary').first().click().catch(() => {});
await pg.waitForFunction(() => window.__lunar.game.phase === 'playing' || window.__lunar.game.phase === 'failure', null, { timeout: 30000 });
await pg.evaluate(() => { const g = window.__lunar.game; if (g.phase === 'playing') { g.crisis = null; } });
// objective chime / critical alarm hooks
await pg.evaluate(() => { const e = window.__lunar; const calls = []; const orig = e.sfx.play.bind(e.sfx); e.sfx.play = (n) => { calls.push(n); orig(n); }; const al = e.sfx.alarms.bind(e.sfx); window.__alarms = []; e.sfx.alarms = (t, a) => { const k = al(t, a); if (k) window.__alarms.push(k); return k; }; window.__calls = calls; });
await pg.evaluate(() => { const g = window.__lunar.game; g.oxygen = 10; });
await pg.waitForFunction(() => window.__alarms.includes('oxygen'), null, { timeout: 90000 });
const n1 = await pg.evaluate(() => window.__alarms.filter((k) => k === 'oxygen').length);
await pg.waitForTimeout(3000);
check('critical oxygen starts ONE warning alarm (not repeated every second)', n1 === 1 && await pg.evaluate(() => window.__alarms.filter((k) => k === 'oxygen').length) === 1);
await pg.evaluate(() => { const g = window.__lunar.game; g.health = 10; });
await pg.waitForTimeout(1000);
check('alarms never stack: a health alarm waits while the oxygen alarm is active', await pg.evaluate(() => !window.__alarms.includes('health')));
await pg.evaluate(() => { const e = window.__lunar, g = e.game; g.oxygen = 100; g.events.push({ type: 'objective', id: 'x' }); });
await pg.waitForFunction(() => window.__calls.includes('chime'), null, { timeout: 60000 });
check('completing an objective plays the chime', true);
console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'no page errors');
check('no page errors', errs.length === 0);
console.log(`${results.filter(Boolean).length}/${results.length} checks passed`);
await b.close(); s.close();
process.exit(results.every(Boolean) ? 0 : 1);
