import { createRequire } from 'node:module';
import path from 'node:path'; import { mkdirSync } from 'node:fs'; import { fileURLToPath } from 'node:url';
import { serve } from './test-serve.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const here = path.dirname(fileURLToPath(import.meta.url));
mkdirSync(path.join(here, 'test-output', 'shots'), { recursive: true });
const s = await serve(path.join(here, 'test-output', 'dist-world')); const port = s.address().port;
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--use-gl=angle'] });
const pg = await b.newPage({ viewport: { width: 960, height: 540 } });
const logs = []; pg.on('console', (m) => logs.push(m.type() + ': ' + m.text())); pg.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 4).join('\n')));
await pg.goto(`http://localhost:${port}/?quality=0.5&scale=0.5`); await pg.waitForTimeout(1500); await pg.evaluate('__lunar.save.progress.unlocked=7');
const shot = async (name, setup) => {
  await pg.evaluate(setup); await pg.waitForTimeout(1200);
  await pg.screenshot({ path: path.join(here, 'test-output', 'shots', `world-${name}.png`) });
};
const place = (x, z, yaw, pitch = 0) => `(g=>{g.player.x=${x};g.player.z=${z};g.player.yaw=${yaw};g.player.pitch=${pitch};})(__lunar.game)`;
const only = (process.argv[2] || '').split(',').filter(Boolean);
const run = async (name, setup) => { if (!only.length || only.includes(name)) await shot(name, setup); };
const faceMate = `(()=>{const g=__lunar.game,m=g.mate;g.player.yaw=Math.atan2(-(m.x-g.player.x),-(m.z-g.player.z));g.player.pitch=0.05;})()`;
await run('moon-arrays', `__lunar.startLevel(1);__lunar.begin();${place(14, 8, -0.9, 0.05)}`);
await run('moon-habitat-in', `${place(0, -2.5, 0.0, -0.05)}`);
await run('moon-mate', `(()=>{const g=__lunar.game;g.player.x=0;g.player.z=24;g.mate.x=1;g.mate.z=19;g.mate.path=[];})()`);
await run('moon-mate2', faceMate);
await run('moon-night-L5', `__lunar.save.progress.unlocked=7;__lunar.startLevel(5);__lunar.begin();${place(0, 26, 0.3, 0.1)};__lunar.game.sun=0.02`);
await run('mars-outside', `__lunar.startLevel(6);__lunar.begin();${place(0, 26, 0.2, 0.05)}`);
await run('mars-greenhouse', `(()=>{const g=__lunar.game;g.sys.greenhouse.st='ok';g.sys.greenhouse.on=true;g.sys.greenhouse.powered=true;${place(-14, -1, 1.57, -0.05)}})()`);
await run('mars-leaks-inside', `(()=>{const g=__lunar.game;g.status.water_leak=true;g.status.o2_leak=true;${place(0, -3, -1.1, -0.1)}})()`);
await run('mars-dust-storm', `(()=>{const g=__lunar.game;g.hazard={type:'dust',state:'active',t:0,dur:100,intensity:1};g.sun=0.04;__lunar.dustMix=1;${place(8, 20, 0.0, 0.05)}})()`);
await run('mars-arrays-stowed', `(()=>{const g=__lunar.game;g.hazard=null;g.sun=0.43;g.arrays.array1='stowed';g.arrays.array2='broken';g.dust.array3=0.8;${place(14, 8, -0.9, 0.05)}})()`);
console.log(logs.join('\n') || 'no console output');
await b.close(); s.close();
